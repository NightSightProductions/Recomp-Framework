#!/usr/bin/env python3
"""Generate win32/runtime/steam32_slots.h from Valve's steam_api.json (Steamworks SDK, public/steam/steam_api.json):
for every interface version, each vtable slot's name, the stack bytes a 32-bit MSVC thiscall callee pops, and how
it returns its result. The runtime's Steam objects use the table to pop exactly what the game pushed.

usage: gen_steam32.py steam_api.json [more.json...] out.h
  several SDK versions can be merged: each adds the interface versions the earlier ones don't have (games ask for
  versions from their own SDK, which newer jsons may have dropped, e.g. SteamUtils010; and older ones lack newer
  versions whose slots moved, e.g. SteamFriends018 has no SetPersonaName)
  steam32_slots.h is built from Steamworks.NET's CodeGen/steam/steam_api.json (github.com/rlabrecque/Steamworks.NET)
  at ea51b02 (2026, SDK with SteamFriends018) followed by 5289ecd (2025-03, SteamFriends017 / SteamUtils010 era)

Return kinds: v void, i eax, q edx:eax (64-bit integers), f st0 (float/double), S hidden return pointer (classes
such as CSteamID / CGameID and structs over 8 bytes: MSVC passes the pointer as the first stack argument, the callee
pops it and returns it in eax).
"""
import json, re, sys

srcs, out = sys.argv[1:-1], sys.argv[-1]
if not srcs or not out.endswith(".h"): sys.exit("usage: gen_steam32.py steam_api.json [more.json...] out.h")
typedefs, enums, structs = {}, set(), {}

def load_types(d):
    global typedefs, enums, structs
    typedefs = {t["typedef"]: t["type"] for t in d.get("typedefs", [])}
    enums = {e["enumname"] for e in d.get("enums", [])}
    for i in d["interfaces"]:
        for e in i.get("enums", []): enums.add(e["enumname"]); enums.add(i["classname"] + "::" + e["enumname"])
    structs = {s["struct"]: s for s in d.get("structs", [])}
    for s in d.get("callback_structs", []): structs[s["struct"]] = s

PRIM = {"void": 0, "bool": 1, "char": 1, "unsigned char": 1, "int8": 1, "uint8": 1, "signed char": 1,
        "short": 2, "unsigned short": 2, "int16": 2, "uint16": 2,
        "int": 4, "unsigned int": 4, "int32": 4, "uint32": 4, "long": 4, "unsigned long": 4, "float": 4,
        "int64": 8, "uint64": 8, "long long": 8, "unsigned long long": 8, "double": 8,
        "intptr_t": 4, "uintptr_t": 4, "size_t": 4, "uint64_steamid": 8, "uint64_gameid": 8}
CLASSES = {"CSteamID", "CGameID"}

def clean(t):
    t = re.sub(r"\bconst\b", "", t).strip()
    t = re.sub(r"\s+", " ", t)
    return t

def size_of(t, depth=0):
    t = clean(t)
    if t.endswith("*") or t.endswith("&") or "[" in t: return 4   # pointers, references, arrays decay
    if t in PRIM: return PRIM[t]
    if t in CLASSES: return 8
    if t in enums or t.split("::")[-1] in enums: return 4
    if t in typedefs and depth < 8: return size_of(typedefs[t], depth + 1)
    if t in structs:
        total = 0
        for f in structs[t]["fields"]:
            ft = f["fieldtype"]
            m = re.search(r"\[(\d+)\]", ft)
            n = int(m.group(1)) if m else 1
            total += size_of(re.sub(r"\s*\[\d+\]", "", ft), depth + 1) * n
        return total
    return None

def kind_of_return(t):
    t = clean(t)
    if t == "void": return "v", 0
    if t.endswith("*") or t.endswith("&"): return "i", 0
    if t in CLASSES: return "S", 4
    base = t
    while base in typedefs: base = clean(typedefs[base])
    if base in ("float", "double"): return "f", 0
    sz = size_of(t)
    if base in structs:
        if sz is not None and sz <= 8 and t not in CLASSES: return ("q" if sz > 4 else "i"), 0
        return "S", 4
    if sz == 8: return "q", 0
    return "i", 0

rows, unknown, seen = [], set(), set()
def add_rows(d):
  for itf in d["interfaces"]:
      # interfaces without a version string in the json (ISteamClient) go in under their family name ("SteamClient"),
      # which the runtime matches against any "SteamClient0NN" request; callback interfaces have no vtable to offer
      ver = itf.get("version_string") or (itf["classname"][1:] if itf["classname"] in ("ISteamClient",) else None)
      if not ver or ver in seen: continue
      seen.add(ver)
      slots = []
      for m in itf["methods"]:
          rk, hidden = kind_of_return(m["returntype"])
          b = hidden
          for p in m.get("params", []):
              s = size_of(p["paramtype"])
              if s is None: unknown.add(p["paramtype"]); s = 4
              b += (s + 3) & ~3   # stack slots are 4-byte aligned
          slots.append((m["methodname"], b, rk))
      rows.append((itf["classname"], ver, slots))

for src in srcs:
    d = json.load(open(src)); load_types(d); add_rows(d)

with open(out, "w") as f:
    f.write("// generated by win32/tools/gen_steam32.py from the Steamworks SDK's steam_api.json: one row per interface\n")
    f.write("// version, one entry per vtable slot {name, stack bytes popped (32-bit thiscall), return kind}\n#pragma once\n")
    f.write("typedef struct { const char *name; unsigned short argbytes; char ret; } SteamSlot;\n")
    f.write("typedef struct { const char *iface, *version; int n; const SteamSlot *slots; } SteamIface;\n")
    for cls, ver, slots in rows:
        f.write("static const SteamSlot ss_%s[] = {\n" % re.sub(r"\W", "_", ver))
        f.write("".join('  {"%s", %d, \'%s\'},\n' % s for s in slots))
        f.write("};\n")
    f.write("static const SteamIface steam_ifaces[] = {\n")
    f.write("".join('  {"%s", "%s", %d, ss_%s},\n' % (cls, ver, len(slots), re.sub(r"\W", "_", ver)) for cls, ver, slots in rows))
    f.write("};\n#define NSTEAM_IFACES %d\n" % len(rows))
print("%d interface versions -> %s" % (len(rows), out))
if unknown: print("types sized as 4 bytes (unknown):", ", ".join(sorted(unknown)))
