#!/usr/bin/env python3
"""Generate runtime/vk_thunks.h: one guest-callable shim per Vulkan command in vulkan_core.h.

Guest (Win64) Vulkan structs have the same layout as host (arm64 macOS) ones, so arguments pass
through unchanged: each thunk reads the Win64 argument slots, casts them to the real parameter
types and calls the host entry point (resolved lazily through vkGetInstanceProcAddr).
  - integer / pointer / handle / enum args come from rcx, rdx, r8, r9, then the stack
  - float args come from xmm0-3 (same position), then the stack
  - const VkAllocationCallbacks* is always passed as NULL (its callbacks are guest code)
Commands that need translation are listed in MANUAL and written by hand in runtime/vulkan.c.

usage: gen_vk.py vulkan_core.h out.h
"""
import re, sys

MANUAL = {
    "vkGetInstanceProcAddr", "vkGetDeviceProcAddr",
    "vkCreateInstance", "vkCreateDevice", "vkCreateSwapchainKHR", "vkQueuePresentKHR", "vkCreateQueryPool", "vkGetQueryPoolResults",
    "vkGetPhysicalDeviceSurfacePresentModesKHR", "vkAcquireNextImageKHR", "vkCreateImage", "vkCreateSampler", "vkCreateImageView",
    "vkCreateShaderModule", "vkCreateGraphicsPipelines", "vkCmdBindPipeline", "vkCmdDrawIndexed", "vkCmdDraw",
    "vkCmdDrawIndexedIndirect", "vkCmdDrawIndirect", "vkCmdDispatch", "vkCmdDispatchIndirect", "vkCreateComputePipelines",
    "vkEnumerateInstanceExtensionProperties",
    "vkCreateDebugReportCallbackEXT", "vkDestroyDebugReportCallbackEXT",
    "vkCreateDebugUtilsMessengerEXT", "vkDestroyDebugUtilsMessengerEXT",
    "vkGetPhysicalDeviceMemoryProperties", "vkGetPhysicalDeviceMemoryProperties2", "vkGetPhysicalDeviceMemoryProperties2KHR",
    "vkAllocateMemory", "vkGetBufferMemoryRequirements", "vkGetImageMemoryRequirements",
    "vkGetBufferMemoryRequirements2", "vkGetImageMemoryRequirements2", "vkGetBufferMemoryRequirements2KHR",
    "vkGetImageMemoryRequirements2KHR", "vkGetDeviceBufferMemoryRequirements", "vkGetDeviceImageMemoryRequirements",
    "vkGetDeviceBufferMemoryRequirementsKHR", "vkGetDeviceImageMemoryRequirementsKHR",
}
RET64 = {"uint64_t", "VkDeviceAddress", "VkDeviceSize"}
RET32 = {"VkResult", "uint32_t", "VkBool32", "int32_t"}

def main(hdr, out):
    src = open(hdr).read()
    protos = re.findall(r"VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\(\s*(.*?)\);", src, re.S)
    seen, lines = set(), []
    for ret, name, params in protos:
        if name in seen or name in MANUAL: continue
        seen.add(name)
        ps = [] if params.strip() == "void" else [" ".join(p.split()) for p in params.split(",")]
        args = []
        for i, p in enumerate(ps):
            m = re.match(r"(.*?)\s*\b(\w+)\s*(\[\w+\])?$", p)
            ty, arr = m.group(1).strip(), m.group(3)
            if arr: ty += "*"
            slot =["A0", "A1", "A2", "A3"][i] if i < 4 else "AN(%d)" % i
            if ty == "const VkAllocationCallbacks*":
                args.append("NULL")
            elif ty == "float":
                args.append("AF(%d)" % i if i < 4 else "rdf(c->rsp + 8 + 8 * %d)" % i)
            elif ty == "double":
                args.append("AD(%d)" % i if i < 4 else "rdd(c->rsp + 8 + 8 * %d)" % i)
            elif "*" in ty or ty.startswith("Vk") or ty in ("uint32_t", "int32_t", "uint64_t", "int64_t", "size_t", "uint16_t", "uint8_t", "int"):
                args.append("(%s)(uintptr_t)%s" % (ty, slot))
            else:
                raise SystemExit("%s: unhandled parameter type %r" % (name, ty))
        call = "p_%s(%s)" % (name, ", ".join(args))
        if ret == "void": body, fail = call + ";", ""
        elif ret == "VkResult":   # failures are logged (once per command and code): a failed pipeline is a missing effect
            body, fail = "{ VkResult r_ = %s; if (r_ < 0) vk_failed(\"%s\", r_); RET((uint32_t)r_); }" % (call, name), "RET((uint32_t)VK_ERROR_EXTENSION_NOT_PRESENT);"
        elif ret in RET32: body, fail = "RET((uint32_t)%s);" % call, "RET(0);"
        elif ret in RET64: body, fail = "RET((uint64_t)%s);" % call, "RET(0);"
        else: raise SystemExit("%s: unhandled return type %r" % (name, ret))
        lines.append("static PFN_%s p_%s;\nvoid I_vulkan_1_dll_%s(CPU *c) { VK_LOAD(%s, %s); %s }\n" % (name, name, name, name, fail, body))
    feats = re.search(r"typedef struct VkPhysicalDeviceFeatures \{(.*?)\} VkPhysicalDeviceFeatures;", src, re.S).group(1)
    fnames = re.findall(r"VkBool32\s+(\w+);", feats)
    lines.append("static const char *const vk_feature_names[] = {\n%s\n};\n" % ",\n".join('    "%s"' % n for n in fnames))
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_vk.py from vulkan_core.h - do not edit.\n")
        f.write("// %d thunks; included by runtime/vulkan.c, which defines VK_LOAD.\n\n" % len(lines))
        f.write("\n".join(lines))
    print("%s: %d thunks (%d hand-written commands skipped)" % (out, len(lines), len(MANUAL)))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
